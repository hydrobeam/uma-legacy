//! Writes the solver's constants fitted in the research from research/results.json: the training-hint constants
//! (src/deck/hints.rs; docs/RESEARCH.md section 7), each rounded to the 3 decimals /about states, so a research rerun
//! moves the solver only when a fitted value moves at that precision, into OUT_DIR/hint_constants.rs, which hints.rs
//! includes; and the career planner's low-basis cost (src/career/schedule.rs; section 4), whole points on the table's
//! scale, into OUT_DIR/race_constants.rs, which schedule.rs includes; and the all-target obs/pred ratio's 95% interval
//! (section 13), rounded to 3 decimals, into OUT_DIR/plan_constants.rs, which the plan's robustness check
//! (src/career/plan/robust.rs) includes.

use std::fmt::Write as _;
use std::{env, fs, path::Path};

/// research/results.json, relative to the crate's directory (CARGO_MANIFEST_DIR)
const RESULTS: &str = "../../research/results.json";
/// the command that recomputes research/results.json
const REGENERATE: &str = "./build.sh research";

/// One constant hints.rs reads: its Rust name, its key in results.json's `values`, and what it is.
struct HintConstant {
    name: &'static str,
    key: &'static str,
    about: &'static str,
}

const fn constant(name: &'static str, key: &'static str, about: &'static str) -> HintConstant {
    HintConstant { name, key, about }
}

/// Bases and specialty weights d per scenario. Grand Masters has no runs: it takes the fit of one base and one d over
/// every other scenario's rows.
const HINT_CONSTANTS: [HintConstant; 10] = [
    constant("BASE_UNITY_CUP", "7.specialty_base_unity_cup", "Unity Cup's base"),
    constant("SPEC_UNITY_CUP", "7.specialty_d_unity_cup", "Unity Cup's specialty weight d"),
    constant("BASE_GRAND_CONCERT", "7.specialty_base_grand_concert", "Grand Concert's base"),
    constant("SPEC_GRAND_CONCERT", "7.specialty_d_grand_concert", "Grand Concert's specialty weight d"),
    constant("BASE_URA_FINALE", "7.specialty_base_ura_finale", "URA Finale's base"),
    constant("SPEC_URA_FINALE", "7.specialty_d_ura_finale", "URA Finale's specialty weight d"),
    constant("BASE_TRACKBLAZER", "7.specialty_base_trackblazer", "Trackblazer's base"),
    constant("SPEC_TRACKBLAZER", "7.specialty_d_trackblazer", "Trackblazer's specialty weight d"),
    constant("BASE_GRAND_MASTERS", "7.one_base_and_one_d_base", "Grand Masters' base, the pooled fit's (no runs)"),
    constant("SPEC_GRAND_MASTERS", "7.one_base_and_one_d_d", "Grand Masters' specialty weight d, the pooled fit's"),
];

/// research/results.json's `values."{key}"`, a number
fn value(results: &serde_json::Value, key: &str) -> f64 {
    results["values"][key].as_f64().unwrap_or_else(|| {
        panic!("research/results.json: `values.\"{key}\"` is missing or not a number; `{REGENERATE}` computes it")
    })
}

/// The career planner's low-basis cost (docs/RESEARCH.md section 4): cells whose aptitude basis (110 - grade costs, on
/// her raised grades) is in the lowest bucket, `4.low_aptitude_basis_bucket` (a label "<=B", B its bound), cost
/// `4.low_basis_cost_fitted_on_every_run` more points. The fit's grid is whole points and the bound a whole basis, both
/// asserted.
fn race_constants(results: &serde_json::Value) -> String {
    const BUCKET: &str = "4.low_aptitude_basis_bucket";
    const COST: &str = "4.low_basis_cost_fitted_on_every_run";
    let bucket = results["values"][BUCKET].as_str().unwrap_or_else(|| {
        panic!("research/results.json: `values.\"{BUCKET}\"` is missing or not a string; `{REGENERATE}` computes it")
    });
    let bound: i32 = bucket.strip_prefix("<=").and_then(|bound| bound.parse().ok()).unwrap_or_else(|| {
        panic!("research/results.json: `values.\"{BUCKET}\"` is {bucket:?}, not \"<=\" and a whole basis")
    });
    let cost = value(results, COST);
    assert!(cost.fract() == 0.0 && cost >= 0.0, "research/results.json: `{COST}` is {cost}, not whole points");
    format!(
        "// Generated by build.rs from research/results.json (docs/RESEARCH.md section 4).\n\
         /// The lowest aptitude-basis bucket's bound: a cell whose basis is at most this takes `LOW_BASIS_COST` (`{BUCKET}`)\n\
         pub(crate) const LOW_BASIS_MAX: i32 = {bound};\n\
         /// The extra aptitude cost there, points (`{COST}`)\n\
         pub(crate) const LOW_BASIS_COST: i32 = {cost:.0};\n"
    )
}

/// The career planner's robustness check (src/career/plan/robust.rs; docs/RESEARCH.md section 13): the ends of the
/// 95% interval of the observed / predicted P(all eight) ratio over every run, each rounded to 3 decimals.
fn plan_constants(results: &serde_json::Value) -> String {
    const LOW: &str = "13.p_all_eight_ratio_all_95_pct_low";
    const HIGH: &str = "13.p_all_eight_ratio_all_95_pct_high";
    let (low, high) = (value(results, LOW), value(results, HIGH));
    assert!(0.0 < low && low <= high, "research/results.json: `{LOW}` {low} and `{HIGH}` {high} are not an interval");
    format!(
        "// Generated by build.rs from research/results.json (docs/RESEARCH.md section 13), rounded to 3 decimals.\n\
         /// The all-target obs/pred ratio's 95% interval, its low end (`{LOW}`)\n\
         const P_ALL_RATIO_LOW: f64 = {low:.3};\n\
         /// Its high end (`{HIGH}`)\n\
         const P_ALL_RATIO_HIGH: f64 = {high:.3};\n"
    )
}

fn main() {
    println!("cargo:rerun-if-changed={RESULTS}");
    println!("cargo:rerun-if-changed=build.rs");
    let crate_dir = env::var("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR for a build script");
    let results_path = Path::new(&crate_dir).join(RESULTS);
    let text = fs::read_to_string(&results_path)
        .unwrap_or_else(|error| panic!("{}: {error}; `{REGENERATE}` writes it", results_path.display()));
    let results: serde_json::Value = serde_json::from_str(&text)
        .unwrap_or_else(|error| panic!("{}: {error}; `{REGENERATE}` rewrites it", results_path.display()));
    let mut code = String::from(
        "// Generated by build.rs from research/results.json (docs/RESEARCH.md section 7), rounded to 3 decimals.\n",
    );
    for hint_constant in &HINT_CONSTANTS {
        let value = value(&results, hint_constant.key);
        writeln!(
            code,
            "/// {} (`{}` in research/results.json)\nconst {}: f64 = {value:.3};",
            hint_constant.about, hint_constant.key, hint_constant.name
        )
        .expect("writing to a String does not fail");
    }
    let out_dir = env::var("OUT_DIR").expect("cargo sets OUT_DIR for a build script");
    for (file, contents) in [
        ("hint_constants.rs", code),
        ("race_constants.rs", race_constants(&results)),
        ("plan_constants.rs", plan_constants(&results)),
    ] {
        let out_path = Path::new(&out_dir).join(file);
        fs::write(&out_path, contents).unwrap_or_else(|error| panic!("{}: {error}", out_path.display()));
    }
}
