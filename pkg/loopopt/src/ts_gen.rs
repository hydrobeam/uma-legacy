//! The page's TypeScript types, generated from the solver's report and job structs by ts-rs: every type reachable
//! from `ROOTS`, in one file (`webapp/src/gen/solver.ts`), sorted by name. `./build.sh types` writes it (this test,
//! then Biome's formatting); `./build.sh lint` regenerates it and fails when the committed file differs.
use std::any::TypeId;
use std::collections::{BTreeMap, HashSet};
use ts_rs::{Config, TS, TypeVisitor};

/// What the file says of itself.
const HEADER: &str = "// Generated by ts-rs from the solver's report and job structs (pkg/loopopt/src/ts_gen.rs): \
                      `./build.sh types`.\n// Never edit it: change the Rust struct and regenerate. `./build.sh lint` \
                      fails when it is stale.\n";

/// Each type's declaration by its TypeScript name, its dependencies visited once each.
struct Declarations<'cfg> {
    cfg: &'cfg Config,
    seen: HashSet<TypeId>,
    by_name: BTreeMap<String, String>,
}

impl TypeVisitor for Declarations<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        // (a primitive or a wrapper has no declaration of its own; ts-rs's own export skips them the same way)
        if T::output_path().is_none() || !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        let name = T::ident(self.cfg);
        let declaration = format!("{}export {}\n", T::docs().unwrap_or_default(), T::decl(self.cfg));
        let earlier = self.by_name.insert(name, declaration);
        assert!(earlier.is_none(), "two types are named {}", T::ident(self.cfg));
        T::visit_dependencies(self);
    }
}

/// The types the page reads or sends; everything they hold follows.
fn visit_roots(declarations: &mut Declarations) {
    declarations.visit::<crate::loop_planner::output::DeckReply>();
    declarations.visit::<crate::career::reply::CareerReply>();
}

/// The file's text, before formatting.
fn solver_ts() -> String {
    // the solver's 64-bit integers are counts and ids well inside a double's exact range
    let cfg = Config::new().with_large_int("number");
    let mut declarations = Declarations { cfg: &cfg, seen: HashSet::new(), by_name: BTreeMap::new() };
    visit_roots(&mut declarations);
    let mut text = String::from(HEADER);
    for declaration in declarations.by_name.values() {
        text.push('\n');
        text.push_str(declaration);
    }
    text
}

/// Writes the file's unformatted text to `TS_GEN_OUT` (`./build.sh types` formats it).
#[test]
#[ignore = "writes the page's types: ./build.sh types"]
fn write_solver_ts() {
    let path = std::env::var("TS_GEN_OUT").expect("TS_GEN_OUT: where to write the generated types");
    std::fs::write(path, solver_ts()).unwrap();
}
